def coping_tools_for(triage: TR.MHTriage, limit: int = 3) -> List[Dict[str, Any]]:
    """Pick a small, relevant set of coping tools for this message (deterministic)."""
    text = TR._norm(triage.raw_message)
    if triage.crisis:
        chosen = ["grounding_54321", "breathing"]
    else:
        chosen: List[str] = []
        if TR._any(text, ["sleep", "insomnia", "can't sleep", "cant sleep", "neend", "नींद"]):
            chosen.append("sleep_support")
        if TR._any(text, ["exam", "study", "work", "job", "office", "deadline", "padhai", "पढ़ाई"]):
            chosen.append("study_work_stress")
        if TR._any(text, ["lonely", "alone", "akela", "akeli", "अकेल", "no one", "nobody"]):
            chosen.append("loneliness")
        if TR._any(text, ["grief", "grieving", "died", "passed away", "loss", "miss ", "lost my",
                          "शोक", "मौत"]):
            chosen.append("grief")
        if TR._any(text, ["panic", "anxiety", "anxious", "worry", "worried", "overwhelm",
                          "ghabra", "घबरा", "डर"]):
            chosen += ["breathing", "grounding_54321", "present_moment"]
        if triage.risk_level == TR.MODERATE:
            chosen += ["breathing", "grounding_54321", "problem_breakdown"]
        chosen += ["breathing", "emotional_labeling"]
    out, seen = [], set()
    for tid in chosen:
        if tid in _TOOLS and tid not in seen:
            seen.add(tid)
            out.append(dict(_TOOLS[tid]))
        if len(out) >= limit:
            break
    return out


