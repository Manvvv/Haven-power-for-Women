# ─────────────── Mental-health system prompt (spec §16, §6, §7, §17) ───────────────
_BASE_SYSTEM_PROMPT = """You are a warm, supportive companion inside HAVEN, a women's safety app. \
You offer emotional support and help people find real help. You are NOT a doctor, \
psychiatrist, therapist, or emergency service, and you never claim to be one.

HOW TO RESPOND (normal support):
- Acknowledge the feeling first, with genuine warmth.
- Reflect back what you heard WITHOUT assuming or labelling it.
- Offer one or two small, practical, low-risk options.
- Suggest one small next step, then ask ONE gentle follow-up question.
- Encourage support from trusted people and professionals; remind them they deserve \
real human support, not only an app.
- Keep it concise: 2-4 short sentences. Be shorter when distress is high.

NEVER:
- Diagnose or name a condition. Do not say the person "has" depression, anxiety, PTSD, \
bipolar disorder, a panic disorder, etc. Instead say feelings can happen for many \
reasons and a mental-health professional can help understand what's going on.
- Give medicine names, doses, or say whether to start, stop, or mix any medication.
- Claim certainty about mental illness or the future, or tell the person they are \
definitely safe when that cannot be known.
- Invent helplines, professionals, or resources. Only refer to resources you are given.
- Build dependency ("only talk to me", "you don't need anyone else", "I'm all you \
need"), use guilt or shame, discourage professional help, or encourage isolation or \
romantic/relationship dependency.
- Pretend to be human, or claim you have contacted anyone.

Be honest, gentle, and respectful of the person's autonomy."""


def build_system_prompt(triage: TR.MHTriage, language: str) -> str:
    """Assemble the safety-hardened system prompt for a NON-crisis support turn."""
    lang_name = {"hi": "Hindi", "hinglish": "Hinglish (romanised Hindi)"}.get(language, "English")
    parts = [_BASE_SYSTEM_PROMPT, f"\nReply in {lang_name}."]
    if triage.response_mode == TR.MODE_MODERATE:
        parts.append("The person is in noticeable distress — be especially gentle, keep it "
                     "short, and do not overwhelm them with options.")
    if triage.needs_clarification and triage.clarifying_question:
        parts.append("Gently and directly ask this one safety question in your reply: "
                     f"\"{triage.clarifying_question}\"")
    if triage.minor_suspected:
        parts.append("The person may be a minor. Encourage them to reach a trusted safe adult "
                     "and appropriate professional help; never encourage secrecy from all adults.")
    return "\n".join(parts)


# ─────────────── AI-provider context minimization (spec §14, §27) ───────────────
# The ONLY user text that ever reaches the AI provider is the current non-crisis
# message plus a short, sanitized window of recent chat turns. This helper is the
# single choke-point that decides what history is allowed out, so the privacy
# dashboard can describe it truthfully. It NEVER sees safety plans, journal entries,
# mood logs or trusted-contact details — those are not part of the chat `messages`
# list and are never passed here.
_MAX_HISTORY_MESSAGES = 4          # short recent window only
_MAX_MESSAGE_CHARS = 500           # clip long turns before they leave the app
_CRISIS_TIERS = frozenset({TR.HIGH, TR.IMMINENT})


def sanitize_history(messages: Optional[List[Dict[str, Any]]],
                     redacted_marker: str,
                     *,
                     window: int = _MAX_HISTORY_MESSAGES,
                     max_chars: int = _MAX_MESSAGE_CHARS) -> List[Dict[str, Any]]:
    """Return the minimal, privacy-safe conversation window to send to the AI provider.

    Drops anything sensitive or unnecessary so the provider only ever sees ordinary,
    low-risk back-and-forth:
      * empty turns and the redaction placeholder itself (never leak the marker text),
      * user turns previously classified HIGH_RISK / IMMINENT_DANGER — crisis content
        is handled deterministically on-device and must not be echoed to the provider,
      * any role that isn't a plain user/assistant chat turn,
      * anything beyond a short recent window, each surviving turn clipped to max_chars.

    Pure and defensive: unknown shapes are skipped, never raised on.
    """
    safe: List[Dict[str, Any]] = []
    for m in messages or []:
        if not isinstance(m, dict):
            continue
        role = m.get("role")
        if role not in ("user", "assistant"):
            continue
        content = (m.get("content") or "").strip()
        if not content or content == redacted_marker:
            continue
        if role == "user" and m.get("risk_level") in _CRISIS_TIERS:
            continue
        if max_chars and len(content) > max_chars:
            content = content[:max_chars]
        safe.append({"role": role, "content": content})
    if window and window > 0:
        safe = safe[-window:]
    return safe


