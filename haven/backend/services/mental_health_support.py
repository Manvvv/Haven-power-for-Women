def _pick_lang(mapping: Dict[str, str], language: str) -> str:
    return mapping.get(language, mapping["en"])


def crisis_response_text(triage: TR.MHTriage) -> str:
    m = _IMMINENT_TEXT if triage.risk_level == TR.IMMINENT else _HIGH_TEXT
    return _pick_lang(m, triage.language)


def medication_safety_text(language: str) -> str:
    return _pick_lang(_MEDICATION_TEXT, language)


def ai_unavailable_text(language: str) -> str:
    return _pick_lang(_AI_DOWN_TEXT, language)


def disclaimer() -> str:
    return DISCLAIMER


def emergency_resources_for(triage: TR.MHTriage) -> List[Dict[str, Any]]:
    """Emergency + crisis resources appropriate to the triage (never fabricated)."""
    child = triage.signals.get("child_safety") and triage.minor_suspected
    women = triage.signals.get("abuse")
    if triage.risk_level == TR.IMMINENT:
        base = R.emergency_resources(child=bool(child), women=bool(women))
        return base + [r for r in R.crisis_resources() if r not in base]
    if triage.crisis:
        return R.crisis_resources()
    return []


